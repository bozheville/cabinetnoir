import React from 'react';
import Head from 'next/head';
import { useRouter } from 'next/router';
import { useTranslation } from 'next-i18next';

import {
  DEFAULT_LOCALE,
  OG_LOCALES,
  SITE_URL,
  alternatesFor,
  languageTag,
  urlFor,
} from '@lib/sitemap-data';

interface SeoProps {
  title: string;
  description: string;
  // Locale-free page path, e.g. `/encoder/caesar/direct` or `/`.
  path: string;
  // schema.org objects, rendered as JSON-LD.
  jsonLd?: Record<string, unknown>[];
  // Site-relative 1200x630 PNG; defaults to the site-wide card.
  image?: string;
  imageAlt?: string;
}

// Generated by scripts/generate-brand-images.js (default) and
// scripts/generate-og-images.js (per cipher). 1200x630 is the 1.91:1
// ratio LinkedIn, Facebook and X need for the large preview card.
const DEFAULT_OG_IMAGE = '/og-image.png';
const OG_IMAGE_WIDTH = 1200;
const OG_IMAGE_HEIGHT = 630;

// Per-page head tags search engines rely on: title, description,
// self-canonical, hreflang alternates for every locale, Open Graph and
// optional structured data.
const Seo: React.FC<SeoProps> = ({
  title,
  description,
  path,
  jsonLd = [],
  image = DEFAULT_OG_IMAGE,
  imageAlt,
}) => {
  const { t } = useTranslation('common');
  const { locale = DEFAULT_LOCALE } = useRouter();
  const canonical = urlFor(path, locale);
  const imageUrl = `${SITE_URL}${image}`;
  const alt = imageAlt || t('name');

  return (
    <Head>
      <title>{title}</title>
      <meta name="description" content={description} />
      <link rel="canonical" href={canonical} />
      {alternatesFor(path).map(({ hrefLang, href }) => (
        <link key={hrefLang} rel="alternate" hrefLang={hrefLang} href={href} />
      ))}
      <meta property="og:type" content="website" />
      <meta property="og:site_name" content={t('name')} />
      <meta property="og:title" content={title} />
      <meta property="og:description" content={description} />
      <meta property="og:url" content={canonical} />
      <meta property="og:locale" content={OG_LOCALES[locale] || OG_LOCALES[DEFAULT_LOCALE]} />
      <meta property="og:image" content={imageUrl} />
      <meta property="og:image:secure_url" content={imageUrl} />
      <meta property="og:image:type" content="image/png" />
      <meta property="og:image:width" content={String(OG_IMAGE_WIDTH)} />
      <meta property="og:image:height" content={String(OG_IMAGE_HEIGHT)} />
      <meta property="og:image:alt" content={alt} />
      <meta name="twitter:card" content="summary_large_image" />
      <meta name="twitter:title" content={title} />
      <meta name="twitter:description" content={description} />
      <meta name="twitter:image" content={imageUrl} />
      <meta name="twitter:image:alt" content={alt} />
      {jsonLd.map((data, index) => (
        <script
          key={index}
          type="application/ld+json"
          dangerouslySetInnerHTML={{
            __html: JSON.stringify({
              '@context': 'https://schema.org',
              inLanguage: languageTag(locale),
              ...data,
            }).replace(/</g, '\\u003c'),
          }}
        />
      ))}
    </Head>
  );
};

Seo.displayName = 'Seo';

export default Seo;
